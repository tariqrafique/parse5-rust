// Regenerates the attribute-span table from parse5 8.0.1 and diffs it against
// crates/parse5/tests/attr_location_spans.rs. Skips when that parse5 is absent.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const parse5Dir = process.env.PARSE5_PATH ?? path.join(root, 'reference/parse5/packages/parse5');

if (!fs.existsSync(path.join(parse5Dir, 'dist/index.js'))) {
  console.log('skipped: run `npm run setup:reference` (parse5 dist is not built)');
  process.exit(0);
}

const generated = spawnSync(process.execPath, [path.join(root, 'scripts/attr-span-reference.mjs'), '--rust'], {
  cwd: root,
  env: { ...process.env, PARSE5_PATH: parse5Dir },
  encoding: 'utf8',
});

if (generated.status !== 0) {
  process.stderr.write(generated.stderr ?? '');
  process.stderr.write(generated.stdout ?? '');
  process.exit(generated.status ?? 1);
}

const testPath = path.join(root, 'crates/parse5/tests/attr_location_spans.rs');
const testSource = fs.readFileSync(testPath, 'utf8');
const marker = '// Generated by scripts/attr-span-reference.mjs';
const start = testSource.indexOf(marker);

if (start < 0) {
  throw new Error(`${testPath} is missing the generated-table marker`);
}

const generatedBody = generated.stdout.slice(generated.stdout.indexOf(marker));
const checkedIn = testSource.slice(start, start + generatedBody.length);

if (checkedIn !== generatedBody) {
  console.error('attribute span table is stale. Regenerate with:');
  console.error('  PARSE5_PATH=reference/parse5/packages/parse5 node scripts/attr-span-reference.mjs --rust');
  process.exit(1);
}

console.log('attribute span table matches parse5 at', parse5Dir);

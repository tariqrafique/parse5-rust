// Generates the reference attribute spans used by
// crates/parse5/tests/attr_location_spans.rs.
//
// Runs parse5 JS (the copy LWC's template compiler uses) with
// `sourceCodeLocationInfo: true` over each case and prints, for every element
// (including template content), the sourceCodeLocation of each attribute.
//
// Usage:
//   node scripts/attr-span-reference.mjs            # JSON
//   node scripts/attr-span-reference.mjs --rust     # Rust table for the test
//   PARSE5_PATH=/path/to/parse5 node scripts/attr-span-reference.mjs
//
// Default parse5 location: reference/parse5/packages/parse5 after
// `npm run setup:reference`. Override with PARSE5_PATH.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const parse5Dir = process.env.PARSE5_PATH ?? path.join(root, 'reference/parse5/packages/parse5');

if (!fs.existsSync(path.join(parse5Dir, 'package.json'))) {
    console.error(`parse5 was not found at ${parse5Dir}`);
    console.error('Run `npm run setup:reference` or set PARSE5_PATH to a parse5 package directory.');
    process.exit(1);
}
const require = createRequire(import.meta.url);
const pkg = require(path.join(parse5Dir, 'package.json'));
const parse5 = await import(path.join(parse5Dir, 'dist/index.js'));

export const CASES = [
    ['quoted_last_gt', '<div a="x">'],
    ['quoted_last_ws_gt', '<div a="x"  >'],
    ['quoted_last_ws_slash_gt', '<div a="x" />'],
    ['quoted_last_slash_gt', '<div a="x"/>'],
    ['single_quoted_last_ws_slash_gt', "<div a='x' />"],
    ['unquoted_last_gt', '<div a=x>'],
    ['unquoted_last_ws_gt', '<div a=x  >'],
    ['unquoted_last_ws_slash_gt', '<div a=x />'],
    ['valueless_last_gt', '<div a>'],
    ['valueless_last_ws_gt', '<div a  >'],
    ['valueless_last_ws_slash_gt', '<div a />'],
    ['valueless_last_slash_gt', '<div a/>'],
    ['empty_value_ws_gt', '<div a= >'],
    ['empty_quoted_ws_slash_gt', '<div a="" />'],
    ['multiple_attrs_ws_slash_gt', '<div a="1" b=2 c d=\'4\' />'],
    ['multiple_attrs_gt', '<div a="1" b=2 c d=\'4\'>'],
    ['multiple_attrs_valueless_last_ws_gt', '<div a="1" b=2 c >'],
    ['self_closing_void_valueless', '<input b />'],
    ['self_closing_void_quoted', '<input type="text" value="v" />'],
    ['self_closing_void_no_space', '<input type="text"/>'],
    ['template_attrs', '<template if:true={x} key="k" ><p class="c" /></template>'],
    ['template_nested_content', '<template><template lwc:if={a}><span b c="d" ></span></template></template>'],
    ['newlines_in_tag', '<div\n  a="x"\n  b\n  c=d\n  e="f"\n/>'],
    ['newline_after_last_attr', '<div a="x"\n>'],
    ['crlf_in_tag', '<div\r\n  a="x"\r\n  b\r\n/>'],
    ['duplicate_attr_last', '<div a="1" a="2" />'],
    ['duplicate_attr_then_other', '<div a="1" a="2" b="3" />'],
    ['missing_ws_between_attrs', '<div a="1"b="2" >'],
    ['char_ref_in_value', '<div a="&amp;x" b=&lt; >'],
    ['multiple_elements', '<div a="x" ></div><span b ></span><img c=d />'],
];

function* walk(node, nodePath) {
    for (const [i, child] of (node.childNodes ?? []).entries()) {
        const childPath = `${nodePath}/${i}`;
        if (child.tagName) {
            yield [childPath, child];
            yield* walk(child, childPath);
            if (child.content) {
                yield* walk(child.content, `${childPath}/content`);
            }
        }
    }
}

const results = CASES.map(([name, html]) => {
    const fragment = parse5.parseFragment(html, { sourceCodeLocationInfo: true });
    const attrs = [];
    for (const [nodePath, el] of walk(fragment, '')) {
        const locs = el.sourceCodeLocation?.attrs ?? {};
        for (const attr of el.attrs) {
            const l = locs[attr.name];
            attrs.push({
                path: nodePath,
                tag: el.tagName,
                name: attr.name,
                value: attr.value,
                loc: [l.startLine, l.startCol, l.startOffset, l.endLine, l.endCol, l.endOffset],
                text: html.slice(l.startOffset, l.endOffset),
            });
        }
    }
    return { name, html, attrs };
});

if (process.argv.includes('--rust')) {
    console.log(`// Generated by scripts/attr-span-reference.mjs from parse5 ${pkg.version}`);
    console.log('// (path, tag, attr, value, [startLine, startCol, startOffset, endLine, endCol, endOffset])');
    for (const { name, html, attrs } of results) {
        console.log(`    (\n        ${JSON.stringify(name)},\n        ${JSON.stringify(html)},\n        &[`);
        for (const a of attrs) {
            console.log(`            (${JSON.stringify(a.path)}, ${JSON.stringify(a.tag)}, ${JSON.stringify(a.name)}, ${JSON.stringify(a.value)}, [${a.loc.join(', ')}]), // ${JSON.stringify(a.text)}`);
        }
        console.log('        ],\n    ),');
    }
} else {
    console.log(JSON.stringify({ parse5: pkg.version, results }, null, 2));
}

fn collect_attr_spans(
    parent: &NodeRef,
    path: &str,
    out: &mut Vec<(String, String, String, String, Option<Span>)>,
) {
    for (index, child) in get_child_nodes(parent)
        .unwrap_or_default()
        .into_iter()
        .enumerate()
    {
        if !child.borrow().is_element() {
            continue;
        }
        let child_path = format!("{path}/{index}");
        let tag = get_tag_name(&child);
        let location = get_node_source_code_location(&child);
        for attr in get_attr_list(&child) {
            let span = location
                .as_ref()
                .and_then(|location| location.attrs.get(&attr.name))
                .map(|l| {
                    [
                        l.start_line,
                        l.start_col,
                        l.start_offset,
                        l.end_line,
                        l.end_col,
                        l.end_offset,
                    ]
                });
            out.push((
                child_path.clone(),
                tag.clone(),
                attr.name.clone(),
                attr.value.clone(),
                span,
            ));
        }
        collect_attr_spans(&child, &child_path, out);
        if let Some(content) = get_template_content(&child) {
            collect_attr_spans(&content, &format!("{child_path}/content"), out);
        }
    }
}

#[test]
fn attr_source_code_locations_match_parse5_js() {
    let options = ParserOptions {
        scripting_enabled: true,
        source_code_location_info: true,
    };
    let mut failures = Vec::new();

    for (name, html, expected) in CASES {
        let fragment = parse_fragment(html, options);
        let mut actual = Vec::new();
        collect_attr_spans(&fragment, "", &mut actual);

        let expected = expected
            .iter()
            .map(|(path, tag, attr, value, span)| {
                (
                    path.to_string(),
                    tag.to_string(),
                    attr.to_string(),
                    value.to_string(),
                    Some(*span),
                )
            })
            .collect::<Vec<_>>();

        if actual != expected {
            failures.push(format!(
                "{name} {html:?}\n  expected (parse5 JS): {expected:?}\n  actual   (rust):      {actual:?}"
            ));
        }
    }

    assert!(
        failures.is_empty(),
        "{} of {} cases differ from parse5 JS:\n{}",
        failures.len(),
        CASES.len(),
        failures.join("\n")
    );
}
